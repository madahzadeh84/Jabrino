/**
 * یکسان‌سازی اولیه ورودی ریاضی
 *
 * وظایف این تابع:
 * - تبدیل ورودی به رشته
 * - حذف فاصله‌ها
 * - تبدیل شکل‌های مختلف علامت ضرب به *
 * - تبدیل علامت تقسیم به /
 *
 * این تابع عمداً وارد اعتبارسنجی یا حل عبارت نمی‌شود.
 */
export function normalize(expr) {
  return String(expr ?? "")
    .replace(/\s+/g, "")
    .replace(/×|&times;|⋅|∙|·/g, "*")
    .replace(/÷/g, "/");
}